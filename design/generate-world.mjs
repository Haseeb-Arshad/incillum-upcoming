import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

/**
 * The world in dots, beside the figures on the front page (`case.tsx`).
 *
 * ```bash
 * npm pack world-atlas@2.0.2 && tar -xzf world-atlas-2.0.2.tgz
 * node design/generate-world.mjs package/land-110m.json
 * ```
 *
 * The land is Natural Earth's 1:110m land, in public domain, as the
 * `world-atlas` package (ISC) ships it as TopoJSON. It is read here as data
 * and nothing in that package is run: the TopoJSON is decoded below, which is
 * twenty lines, rather than through `topojson-client`, so the site carries no
 * dependency for a picture that changes never.
 *
 * Every dot is the centre of a cell on a regular grid in the Miller
 * projection — even rows and columns, as a dot map is — kept if it falls on
 * land. The grid is the reference map's own crop: Alaska to the Caspian,
 * the Americas whole, the Atlantic, and Europe and Africa running off the
 * right-hand edge. `src/lib/world.ts` is the output, committed; this is how it
 * was made.
 */

const here = dirname(fileURLToPath(import.meta.url))
const source = process.argv[2]
if (!source) {
  console.error('usage: node design/generate-world.mjs <land-110m.json>')
  process.exit(1)
}

/** The grid: degrees a cell, and the box it covers. The component projects with the same numbers. */
const grid = { step: 2.5, west: -170, east: 62, north: 76, south: -56 }

const radians = (degrees) => (degrees * Math.PI) / 180
/** Miller's cylindrical projection, y only: x is longitude as it is. */
const miller = (latitude) =>
  1.25 * Math.log(Math.tan(Math.PI / 4 + 0.4 * radians(latitude)))
const inverse = (y) =>
  ((2.5 * Math.atan(Math.exp(y / 1.25)) - (5 * Math.PI) / 8) * 180) / Math.PI

const topology = JSON.parse(await readFile(source, 'utf8'))
const { scale, translate } = topology.transform

/** Arcs are quantised and delta-encoded: undo both. */
const arcs = topology.arcs.map((arc) => {
  let x = 0
  let y = 0
  return arc.map(([dx, dy]) => {
    x += dx
    y += dy
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]]
  })
})

/** A ring is a list of arc indices; `~i` is arc `i` reversed. Consecutive arcs share an end point. */
function ring(indices) {
  const points = []
  for (const index of indices) {
    const arc = index < 0 ? [...arcs[~index]].reverse() : arcs[index]
    points.push(...(points.length ? arc.slice(1) : arc))
  }
  return points
}

const rings = topology.objects.land.geometries.flatMap((geometry) =>
  geometry.type === 'Polygon'
    ? geometry.arcs.map(ring)
    : geometry.arcs.flatMap((polygon) => polygon.map(ring)),
)

/** Even-odd across every ring, so a lake inside a continent is water. */
function onLand(longitude, latitude) {
  let inside = false
  for (const points of rings) {
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [xi, yi] = points[i]
      const [xj, yj] = points[j]
      if (
        yi > latitude !== yj > latitude &&
        longitude < ((xj - xi) * (latitude - yi)) / (yj - yi) + xi
      ) {
        inside = !inside
      }
    }
  }
  return inside
}

const top = miller(grid.north)
const bottom = miller(grid.south)
const pitch = radians(grid.step)
const columns = Math.round((grid.east - grid.west) / grid.step)
const rows = Math.round((top - bottom) / pitch)

const land = []
for (let row = 0; row < rows; row += 1) {
  const latitude = inverse(top - (row + 0.5) * pitch)
  let line = ''
  for (let column = 0; column < columns; column += 1) {
    line += onLand(grid.west + (column + 0.5) * grid.step, latitude) ? '#' : '.'
  }
  land.push(line)
}

const output = `/**
 * The world in dots — generated by \`design/generate-world.mjs\` from Natural
 * Earth's 1:110m land (public domain). Do not edit by hand; run the generator.
 *
 * One string per row, north to south, one character per cell: \`#\` is land.
 * Cells are \`step\` degrees of longitude wide and as tall in Miller's
 * projection, from \`west\` to \`east\` and \`north\` to \`south\`.
 */
export const world = {
  step: ${grid.step},
  west: ${grid.west},
  east: ${grid.east},
  north: ${grid.north},
  south: ${grid.south},
  columns: ${columns},
  rows: ${rows},
  land: [
${land.map((line) => `    '${line}',`).join('\n')}
  ],
} as const
`

await writeFile(resolve(here, '../src/lib/world.ts'), output)
console.log(`${columns} × ${rows} cells, ${land.join('').split('#').length - 1} on land`)
