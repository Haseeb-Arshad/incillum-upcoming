/**
 * Writes icons.js: the icons the film uses, as SVG strings, from the product's
 * own icon set (here Lucide, as lucide-react ships it).
 *
 *   node build-icons.mjs <lucide-react/dist/esm/icons dir> <out icons.js> mail table clock ...
 *
 * Use the version the product itself uses, so the film's icons are the product's.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const [dir, out, ...names] = process.argv.slice(2)
const icons = {}
for (const name of names) {
  const file = ['mjs', 'js'].map((extension) => path.join(dir, `${name}.${extension}`)).find((candidate) => existsSync(candidate))
  if (!file) throw new Error(`no icon named ${name} in ${dir}`)
  const source = readFileSync(file, 'utf8')
  const nodes = JSON.parse(source.match(/const __iconNode = (\[[\s\S]*?\]);\n/)[1].replace(/(\w+):/g, '"$1":'))
  const body = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${value}"`).join(' ')}/>`).join('')
  icons[name] = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`
}
writeFileSync(out, `// Generated by build-icons.mjs. Do not edit.\nwindow.ICONS = ${JSON.stringify(icons, null, 1)}\n`)
console.log('wrote', Object.keys(icons).length, 'icons to', out)
