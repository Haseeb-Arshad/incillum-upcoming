/**
 * Writes marks.js: the full-colour file marks the film's sources wear, from
 * Iconify's packaged sets — vscode-icons (MIT) for Excel, Word, PowerPoint,
 * PDF, CSV and image files, Simple Icons (CC0) for a shared Google Sheet, in
 * its own green.
 *
 *   npm pack @iconify-json/vscode-icons @iconify-json/simple-icons   (into an empty folder, then untar each)
 *   node build-marks.mjs <that folder> marks.js
 *
 * Documents only. The site names no ERP, CRM or mail client (AGENTS.md §5), so
 * no such mark belongs here: an email is Lucide's envelope, as in the product.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const [dir, out] = process.argv.slice(2)
const load = (prefix) => {
  const folder = readdirSync(dir).find((name) => name.startsWith(prefix) && !name.endsWith('.tgz'))
  return JSON.parse(readFileSync(path.join(dir, folder, 'package', 'icons.json'), 'utf8'))
}
const sets = { vscode: load('iconify-json-vscode-icons'), simple: load('iconify-json-simple-icons') }
const pick = {
  excel: ['vscode', 'file-type-excel2'],
  word: ['vscode', 'file-type-word2'],
  powerpoint: ['vscode', 'file-type-powerpoint2'],
  pdf: ['vscode', 'file-type-pdf2'],
  csv: ['vscode', 'file-type-csv'],
  image: ['vscode', 'file-type-image'],
  sheets: ['simple', 'googlesheets', '#34A853'],
}
const marks = {}
for (const [key, [set, name, fill]] of Object.entries(pick)) {
  const source = sets[set]
  const icon = source.icons[name]
  const width = icon.width ?? source.width ?? 16
  const height = icon.height ?? source.height ?? 16
  const body = fill ? `<g fill="${fill}">${icon.body.replaceAll('currentColor', fill)}</g>` : icon.body
  marks[key] = `<svg viewBox="${icon.left ?? 0} ${icon.top ?? 0} ${width} ${height}" aria-hidden="true">${body}</svg>`
}
writeFileSync(out, `// Generated by build-marks.mjs from Iconify's vscode-icons (MIT) and Simple Icons (CC0). Do not edit.\nwindow.MARKS = ${JSON.stringify(marks, null, 1)}\n`)
console.log('wrote', Object.keys(marks).length, 'marks to', out)
