/**
 * Writes `icons.js`: the Lucide icons the film uses, as SVG strings.
 *
 *   node video/charlie/build-icons.mjs <lucide-react esm icons directory>
 *
 * Lucide is the icon set Studio itself uses (`@incillum/icons`), at the same
 * release, so the film's icons are the product's.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const dir = process.argv[2]
const names = ['mail', 'paperclip', 'file-text', 'file-spreadsheet', 'scan-text', 'link-2', 'quote', 'check', 'circle-check', 'send-horizontal', 'scale', 'shield-check', 'mouse-pointer-2', 'clock', 'inbox', 'table', 'pen-line', 'user-check', 'sheet']
const icons = {}
for (const name of names) {
  const source = readFileSync(path.join(dir, `${name}.mjs`), 'utf8')
  const nodes = JSON.parse(source.match(/const __iconNode = (\[[\s\S]*?\]);\n/)[1].replace(/(\w+):/g, '"$1":').replace(/"(\w+)"(?=\s*:)/g, '"$1"'))
  const body = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([key]) => key !== 'key').map(([key, value]) => `${key}="${value}"`).join(' ')}/>`).join('')
  icons[name] = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`
}
writeFileSync(path.join(here, 'icons.js'), `// Generated by build-icons.mjs from lucide-react 1.27.0 (ISC). Do not edit.\nwindow.ICONS = ${JSON.stringify(icons, null, 1)}\n`)
console.log('wrote', Object.keys(icons).length, 'icons')
